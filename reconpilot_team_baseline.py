def parse_nmap_xml(xml_path):
    tree = ET.parse(xml_path)
    root = tree.getroot()

    results = []

    for host_node in root.findall("host"):
        ip = "unknown"

        for addr_node in host_node.findall("address"):
            if addr_node.get("addrtype") == "ipv4":
                ip = addr_node.get("addr")
                break

        host_data = {
            "ip": ip,
            "ports": []
        }

        ports_node = host_node.find("ports")

        if ports_node is None:
            results.append(host_data)
            continue

        for port_node in ports_node.findall("port"):
            state_node = port_node.find("state")

            state = (
                state_node.get("state", "unknown")
                if state_node is not None
                else "unknown"
            )

            service_node = port_node.find("service")

            service = "unknown"
            product = ""
            version = ""

            if service_node is not None:
                service = service_node.get("name", "unknown")
                product = service_node.get("product", "")
                version = service_node.get("version", "")

            host_data["ports"].append({
                "port": port_node.get("portid"),
                "protocol": port_node.get("protocol", "unknown"),
                "state": state,
                "service": service,
                "product": product,
                "version": version,
                "banner": f"{product} {version}".strip(),
            })

        results.append(host_data)

    return {
        "targets": results
    }


def get_open_ports(scan_data):
    open_ports = []

    for target in scan_data["targets"]:
        for port in target["ports"]:
            if port["state"] == "open":
                open_ports.append({
                    "target": target["ip"],
                    "port": port["port"],
                    "protocol": port["protocol"],
                    "service": port["service"],
                    "product": port["product"] or "unknown",
                    "version": port["version"] or "unknown",
                    "banner": port["banner"] or "unknown",
                })

    return open_ports


