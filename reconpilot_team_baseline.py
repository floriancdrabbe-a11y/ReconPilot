def build_what_to_record(action, evidence):
    base = (
        f"Record target {evidence['target']}, port "
        f"{evidence['port']}, protocol {evidence['protocol']}, "
        f"service {evidence['service']}, product "
        f"{evidence['product']}, version {evidence['version']} "
        f"and the evidence source."
    )

    if action == "check_known_vulnerability_references":
        return (
            base
            + " Also record any reference identifier, "
            + "affected-version information and why the "
            + "reference may or may not apply."
        )

    if action == "identify_service_version":
        return (
            base
            + " Record the method used to obtain any new "
            + "version information."
        )

    if action == "collect_service_banner":
        return (
            base
            + " Record the new banner or protocol information "
            + "exactly as observed."
        )

    return (
        base
        + " Record what additional evidence was collected and "
        + "whether it changed the recommended next step."
    )


def build_stop_condition(action):
    if action == "check_known_vulnerability_references":
        return (
            "Stop before any active vulnerability validation, "
            "authentication attempt or exploitation step. "
            "Human review and approval are required first."
        )

    return (
        "Stop once the requested reconnaissance evidence has "
        "been collected. Review the new evidence before moving "
        "to a more active testing stage."
    )


def build_workflow_priority(action):
    if action == "check_known_vulnerability_references":
        return "Review now", 3

    if action in (
        "identify_service_version",
        "collect_service_banner"
    ):
        return "Gather information next", 2

    return "Needs more evidence", 1


def build_guided_result(evidence, llm_result):
    action = llm_result[
        "recommended_next_step"
    ]

    workflow_priority, priority_score = (
        build_workflow_priority(action)
    )

    return {
        "target": evidence["target"],
        "port": evidence["port"],
        "protocol": evidence["protocol"],
        "service": evidence["service"],
        "product": evidence["product"],
        "version": evidence["version"],
        "banner": evidence["banner"],

        "finding": build_finding_summary(
            evidence
        ),

        "what_this_means": (
            SERVICE_DESCRIPTIONS.get(
                evidence["service"],
                DEFAULT_SERVICE_DESCRIPTION
            )
        ),

        "why_it_matters": build_why_it_matters(
            evidence
        ),

        "recommended_action_code": action,

        "recommended_next_step": build_action_label(
            action,
            evidence
        ),

        "why_this_step": build_action_reason(
            action,
            evidence
        ),

        "what_to_do_next": build_what_to_do_next(
            action,
            evidence
        ),

        "what_to_look_for": build_what_to_look_for(
            action,
            evidence
        ),

        "why_this_helps": build_why_this_helps(
            action
        ),

        "what_to_record": build_what_to_record(
            action,
            evidence
        ),

        "stop_condition": build_stop_condition(
            action
        ),

        "workflow_priority": workflow_priority,
        "priority_score": priority_score,
        "confidence": llm_result["confidence"],
        "allowed_actions": llm_result[
            "allowed_actions"
        ],
        "risk": "not_assessed",
        "validation": "pass"
    }


