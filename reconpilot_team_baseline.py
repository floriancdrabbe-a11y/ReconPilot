def is_unknown(value):
    if value is None:
        return True

    value = str(value).strip().lower()

    return value in ("", "unknown")


def is_broad_version(version):
    if is_unknown(version):
        return False

    value = str(version).lower()

    return (
        "x" in value
        or " - " in value
        or "–" in value
    )


def display_product(evidence):
    if not is_unknown(evidence["product"]):
        return evidence["product"]

    return evidence["service"].upper()


def build_allowed_actions(evidence):
    allowed_actions = []

    if (
        is_unknown(evidence["version"])
        or is_broad_version(evidence["version"])
    ):
        allowed_actions.append(
            "identify_service_version"
        )

    elif is_unknown(evidence["banner"]):
        allowed_actions.append(
            "collect_service_banner"
        )

    else:
        allowed_actions.append(
            "check_known_vulnerability_references"
        )

    allowed_actions.append(
        "request_more_evidence"
    )

    return allowed_actions


